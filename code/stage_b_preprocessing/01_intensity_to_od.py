# End-to-end test function — Tasks 3.1.1–3.1.5 on subject A1
# ---------------------------------------------------------------------------

def run_intensity_to_od(
    dataset_name: str,
    subject_id: str,
    verbose: bool = True,
) -> dict:
    """
    Run the full Step B1 pipeline (Tasks 3.1.1–3.1.5) for one subject.

    Steps executed in order:
    1. Load Stage A exclusion list (3.1.1)
    2. Load raw intensity data, mark bad channels (3.1.2)
    3. Convert intensity → OD (3.1.3)
    4. Verify OD range [0.1, 2.0] (3.1.4)
    5. Save verification CSV + OD time series plot (3.1.5)

    Parameters
    ----------
    dataset_name : str
        Dataset key (e.g., 'expert_novice')
    subject_id : str
        Subject identifier (e.g., 'A1')
    verbose : bool
        Print detailed progress

    Returns
    -------
    results : dict
        {
          'raw_od':          mne.io.Raw (OD object),
          'od_df':           pd.DataFrame (range verification),
          'exclusion_data':  dict (Stage A exclusion list),
          'marked_channels': list[str],
          'fig_path':        Path,
          'csv_path':        Path,
        }
    """
    config = load_config()
    stage_b_params = get_stage_params('stage_b', config)
    od_params = stage_b_params['optical_density']

    print("\n" + "=" * 70)
    print(f"STAGE B — STEP B1: INTENSITY TO OD  |  Subject: {subject_id}")
    print("=" * 70 + "\n")

    # ---- 3.1.1 Load exclusion list ----------------------------------------
    exclusion_data = load_exclusion_list(subject_id, verbose=verbose)

    # ---- Load raw intensity ------------------------------------------------
    if verbose:
        print("Loading raw intensity data...")
    raw, _ = load_raw_snirf(dataset_name, subject_id, preload=True, verbose=False)

    # ---- 3.1.2 Mark bad channels ------------------------------------------
    marked_channels = mark_bad_channels(raw, exclusion_data, verbose=verbose)

    # ---- 3.1.3 Convert to OD ----------------------------------------------
    raw_od = convert_to_optical_density(raw, verbose=verbose)

    # ---- 3.1.4 Verify OD range --------------------------------------------
    od_df = verify_od_range(
        raw_od,
        od_min=od_params['valid_range_min'],
        od_max=od_params['valid_range_max'],
        verbose=verbose,
    )

    # ---- 3.1.5 Save outputs + visualize -----------------------------------
    output_dir = get_output_path('stage_b', f'od_conversion/{subject_id}')

    csv_path = save_od_verification(od_df, subject_id, output_dir)

    fig_path = plot_od_time_series(
        raw_od,
        od_df,
        subject_id=subject_id,
        output_dir=output_dir,
        verbose=verbose,
    )

    print("\n" + "=" * 70)
    print(f"✅ Step B1 complete for subject {subject_id}")
    n_ok = int((od_df['od_anomaly_flag'] == 'ok').sum())
    n_bad_ch = int((od_df['od_anomaly_flag'] == 'bad_channel').sum())
    n_anomaly = int(
        ((od_df['od_anomaly_flag'] == 'below_min') |
         (od_df['od_anomaly_flag'] == 'above_max')).sum()
    )
    print(f"  Channels OK:     {n_ok}")
    print(f"  Channels bad:    {n_bad_ch}  (from Stage A exclusion)")
    print(f"  OD anomalies:    {n_anomaly}  (outside [0.1, 2.0])")
    print(f"  Outputs saved:   {output_dir}")
    print("=" * 70 + "\n")

    return {
        'raw_od': raw_od,
        'od_df': od_df,
        'exclusion_data': exclusion_data,
        'marked_channels': marked_channels,
        'fig_path': fig_path,
        'csv_path': csv_path,
    }


