# Task 3.1.5 — Visualize OD time series for sample channels
# ---------------------------------------------------------------------------

def plot_od_time_series(
    raw_od,
    od_df: pd.DataFrame,
    subject_id: str,
    output_dir: Path,
    n_good: int = 3,
    n_bad: int = 2,
    t_max_seconds: float = 120.0,
    verbose: bool = True,
) -> Path:
    """
    Task 3.1.5: Visualize OD time series for a sample of good and bad
    channels to confirm the conversion and highlight flagged channels.

    Shows the first ``t_max_seconds`` of recording for clarity.

    Parameters
    ----------
    raw_od : mne.io.Raw
        Optical density data
    od_df : pd.DataFrame
        Output of verify_od_range()
    subject_id : str
        Subject identifier (used for plot title and filename)
    output_dir : Path
        Directory to save the figure
    n_good : int
        Number of 'ok' channels to plot
    n_bad : int
        Number of flagged/bad channels to plot
    t_max_seconds : float
        Maximum time window to show (seconds)
    verbose : bool
        Print save path

    Returns
    -------
    fig_path : Path
        Path to saved figure
    """
    sfreq = raw_od.info['sfreq']
    n_samples_plot = int(t_max_seconds * sfreq)

    # Select sample channels
    good_channels = od_df[od_df['od_anomaly_flag'] == 'ok']['channel'].tolist()
    flagged_channels = od_df[od_df['od_anomaly_flag'] != 'ok']['channel'].tolist()

    # Pick representative channels: spread across indices for variety
    step = max(1, len(good_channels) // n_good)
    sample_good = good_channels[::step][:n_good]
    sample_flagged = flagged_channels[:n_bad]

    all_channels = sample_good + sample_flagged
    n_plots = len(all_channels)

    if n_plots == 0:
        print("No channels to plot.")
        return None

    fig, axes = plt.subplots(
        n_plots, 1,
        figsize=(14, 2.5 * n_plots),
        sharex=True,
    )
    if n_plots == 1:
        axes = [axes]

    data = raw_od.get_data()
    times = raw_od.times
    ch_names_list = raw_od.ch_names

    plot_end = min(n_samples_plot, len(times))
    t_plot = times[:plot_end]

    for ax, ch_name in zip(axes, all_channels):
        ch_idx = ch_names_list.index(ch_name)
        ch_data = data[ch_idx, :plot_end]

        flag = od_df.loc[od_df['channel'] == ch_name, 'od_anomaly_flag'].values[0]
        mean_od = od_df.loc[od_df['channel'] == ch_name, 'mean_od'].values[0]

        if flag == 'ok':
            color = '#1f77b4'
            label_suffix = f'[ok | mean={mean_od:.3f}]'
            alpha = 0.85
        elif flag == 'bad_channel':
            color = '#d62728'
            label_suffix = f'[BAD (Stage A) | mean={mean_od:.3f}]'
            alpha = 0.7
        else:
            color = '#ff7f0e'
            label_suffix = f'[ANOMALY: {flag} | mean={mean_od:.3f}]'
            alpha = 0.7

        ax.plot(t_plot, ch_data, color=color, lw=0.8, alpha=alpha)
        ax.set_ylabel('OD', fontsize=9)
        ax.set_title(f'{ch_name}  {label_suffix}', fontsize=9, loc='left')
        ax.axhline(0.1, color='green', ls='--', lw=0.8, alpha=0.6, label='OD min (0.1)')
        ax.axhline(2.0, color='red', ls='--', lw=0.8, alpha=0.6, label='OD max (2.0)')
        ax.legend(fontsize=7, loc='upper right')

    axes[-1].set_xlabel('Time (s)', fontsize=10)
    fig.suptitle(
        f'Subject {subject_id} — Optical Density Time Series (first {t_max_seconds:.0f} s)',
        fontsize=12,
        fontweight='bold',
        y=1.01,
    )
    plt.tight_layout()

    output_dir.mkdir(parents=True, exist_ok=True)
    fig_path = output_dir / f"{subject_id}_od_time_series.png"
    fig.savefig(fig_path, dpi=150, bbox_inches='tight')
    plt.close(fig)

    if verbose:
        print(f"Saved OD time series plot: {fig_path}")

    return fig_path


