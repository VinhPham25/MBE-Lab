def mark_bad_channels(
    raw,
    exclusion_data: dict,
    verbose: bool = True,
) -> list:
    """
    Task 3.1.2: Mark Stage A exclusion candidates as bad channels in the
    raw MNE object before any preprocessing step.

    Only channels that are actually present in raw.ch_names are marked.
    This protects against stale JSONs referencing renamed channels.

    Parameters
    ----------
    raw : mne.io.Raw
        Raw fNIRS data (intensity, preloaded)
    exclusion_data : dict
        Output of load_exclusion_list()
    verbose : bool
        Print summary to console

    Returns
    -------
    marked_channels : list[str]
        Channel names actually added to raw.info['bads']
    """
    candidate_bads = exclusion_data.get('bad_channels', [])
    present_channels = set(raw.ch_names)

    # Intersect: only mark channels that exist in this recording
    to_mark = [ch for ch in candidate_bads if ch in present_channels]
    not_found = [ch for ch in candidate_bads if ch not in present_channels]

    # Add to raw.info['bads'] (MNE convention; avoids duplicates)
    existing_bads = set(raw.info['bads'])
    new_bads = [ch for ch in to_mark if ch not in existing_bads]
    raw.info['bads'] = sorted(existing_bads | set(to_mark))

    if verbose:
        print("\n" + "=" * 70)
        print("BAD CHANNELS MARKED (TASK 3.1.2)")
        print("=" * 70)
        print(f"Candidates from Stage A:   {len(candidate_bads)}")
        print(f"Found in this recording:   {len(to_mark)}")
        print(f"Newly added to bads:       {len(new_bads)}")
        if not_found:
            print(f"Not found (skipped):       {len(not_found)}")
            for ch in not_found:
                print(f"  - {ch}")
        print(f"\nraw.info['bads'] ({len(raw.info['bads'])} total):")
        for ch in raw.info['bads']:
            print(f"  - {ch}")
        print("=" * 70 + "\n")

    return to_mark


