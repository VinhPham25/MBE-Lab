# Task 3.1.1 — Load exclusion list from Stage A
# ---------------------------------------------------------------------------

def load_exclusion_list(subject_id: str, verbose: bool = True) -> dict:
    """
    Task 3.1.1: Load the Stage A signal-amplitude exclusion list JSON.

    The JSON is generated by Stage A Step 2.5 and stored at:
      outputs/stage_a_qa/channel_signal_quality_exclusion/
          {subject_id}_exclusion_list_preview.json

    Parameters
    ----------
    subject_id : str
        Subject identifier (e.g., 'A1')
    verbose : bool
        Print summary to console

    Returns
    -------
    exclusion_data : dict
        Keys:
        - subject_id       (str)
        - bad_channels     (list[str])  channels below 80 dB or above 140 dB
        - good_channels    (list[str])
        - exclusion_reasons (dict)     channel -> reason string
        - thresholds_db    (dict)       {'low': 80.0, 'high': 140.0}

    Raises
    ------
    FileNotFoundError
        If the Stage A exclusion JSON has not been generated yet.
    """
    exclusion_dir = get_output_path(
        'stage_a', 'channel_signal_quality_exclusion'
    )
    json_path = exclusion_dir / f"{subject_id}_exclusion_list_preview.json"

    if not json_path.exists():
        raise FileNotFoundError(
            f"Stage A exclusion list not found for subject '{subject_id}'.\n"
            f"Expected path: {json_path}\n"
            "Run code/stage_a_raw_qa/08_signal_amplitude_exclusion.py first."
        )

    with open(json_path, 'r') as f:
        exclusion_data = json.load(f)

    if verbose:
        n_bad = len(exclusion_data.get('bad_channels', []))
        n_good = len(exclusion_data.get('good_channels', []))
        thresholds = exclusion_data.get('thresholds_db', {})
        print("\n" + "=" * 70)
        print("STAGE A EXCLUSION LIST LOADED (TASK 3.1.1)")
        print("=" * 70)
        print(f"Subject:          {exclusion_data['subject_id']}")
        print(f"Source file:      {json_path.name}")
        print(f"Amplitude range:  [{thresholds.get('low', '?')}, "
              f"{thresholds.get('high', '?')}] dB")
        print(f"Good channels:    {n_good}")
        print(f"Bad channels:     {n_bad}")
        if n_bad > 0:
            print("  Candidate exclusions:")
            reasons = exclusion_data.get('exclusion_reasons', {})
            for ch in exclusion_data['bad_channels']:
                reason = reasons.get(ch, 'unknown')
                print(f"    - {ch}  ({reason})")
        print("=" * 70 + "\n")

    return exclusion_data


# ---------------------------------------------------------------------------
# Task 3.1.2 — Mark bad channels in raw.info['bads']
# ---------------------------------------------------------------------------

def mark_bad_channels(
    raw,
    exclusion_data: dict,
    verbose: bool = True,
) -> list:
    """
    Task 3.1.2: Mark Stage A exclusion candidates as bad channels in the
    raw MNE object before any preprocessing step.

    Only channels that are actually present in raw.ch_names are marked.
    This protects against stale JSONs referencing renamed channels.

    Parameters
    ----------
    raw : mne.io.Raw
        Raw fNIRS data (intensity, preloaded)
    exclusion_data : dict
        Output of load_exclusion_list()
    verbose : bool
        Print summary to console

    Returns
    -------
    marked_channels : list[str]
        Channel names actually added to raw.info['bads']
    """
    candidate_bads = exclusion_data.get('bad_channels', [])
    present_channels = set(raw.ch_names)

    # Intersect: only mark channels that exist in this recording
    to_mark = [ch for ch in candidate_bads if ch in present_channels]
    not_found = [ch for ch in candidate_bads if ch not in present_channels]

    # Add to raw.info['bads'] (MNE convention; avoids duplicates)
    existing_bads = set(raw.info['bads'])
    new_bads = [ch for ch in to_mark if ch not in existing_bads]
    raw.info['bads'] = sorted(existing_bads | set(to_mark))

    if verbose:
        print("\n" + "=" * 70)
        print("BAD CHANNELS MARKED (TASK 3.1.2)")
        print("=" * 70)
        print(f"Candidates from Stage A:   {len(candidate_bads)}")
        print(f"Found in this recording:   {len(to_mark)}")
        print(f"Newly added to bads:       {len(new_bads)}")
        if not_found:
            print(f"Not found (skipped):       {len(not_found)}")
            for ch in not_found:
                print(f"  - {ch}")
        print(f"\nraw.info['bads'] ({len(raw.info['bads'])} total):")
        for ch in raw.info['bads']:
            print(f"  - {ch}")
        print("=" * 70 + "\n")

    return to_mark


# ---------------------------------------------------------------------------
# Task 3.1.3 — Optical density conversion
# ---------------------------------------------------------------------------

def convert_to_optical_density(raw, verbose: bool = True):
    """
    Task 3.1.3: Convert raw intensity to optical density (OD) using MNE.

    Uses mne.preprocessing.nirs.optical_density(), which applies the
    Beer-Lambert-compatible transform:
        OD = -log(I / I₀)
    where I₀ is the mean intensity per channel.

    Channels listed in raw.info['bads'] are retained in the OD object
    (they remain marked as bad for downstream steps to handle).

    Parameters
    ----------
    raw : mne.io.Raw
        Raw intensity data (preloaded). Bad channels should already be
        marked (Task 3.1.2) before calling this function.
    verbose : bool
        Print progress information

    Returns
    -------
    raw_od : mne.io.Raw
        Optical density data object with channel type 'fnirs_od'
    """
    if verbose:
        print("Converting raw intensity → optical density...")
        print(f"  Channels in raw.info['bads']: {raw.info['bads']}")

    raw_od = mne.preprocessing.nirs.optical_density(raw, verbose=verbose)

    if verbose:
        n_bad = len(raw_od.info['bads'])
        print(f"✓ OD conversion complete.")
        print(f"  Output channel type: fnirs_od")
        print(f"  Shape: {raw_od.get_data().shape}  "
              f"(channels × samples)")
        print(f"  Bad channels preserved: {n_bad}\n")

    return raw_od


