def load_exclusion_list(subject_id: str, verbose: bool = True) -> dict:
    """
    Task 3.1.1: Load the Stage A signal-amplitude exclusion list JSON.

    The JSON is generated by Stage A Step 2.5 and stored at:
      outputs/stage_a_qa/channel_signal_quality_exclusion/
          {subject_id}_exclusion_list_preview.json

    Parameters
    ----------
    subject_id : str
        Subject identifier (e.g., 'A1')
    verbose : bool
        Print summary to console

    Returns
    -------
    exclusion_data : dict
        Keys:
        - subject_id       (str)
        - bad_channels     (list[str])  channels below 80 dB or above 140 dB
        - good_channels    (list[str])
        - exclusion_reasons (dict)     channel -> reason string
        - thresholds_db    (dict)       {'low': 80.0, 'high': 140.0}

    Raises
    ------
    FileNotFoundError
        If the Stage A exclusion JSON has not been generated yet.
    """
    exclusion_dir = get_output_path(
        'stage_a', 'channel_signal_quality_exclusion'
    )
    json_path = exclusion_dir / f"{subject_id}_exclusion_list_preview.json"

    if not json_path.exists():
        raise FileNotFoundError(
            f"Stage A exclusion list not found for subject '{subject_id}'.\n"
            f"Expected path: {json_path}\n"
            "Run code/stage_a_raw_qa/08_signal_amplitude_exclusion.py first."
        )

    with open(json_path, 'r') as f:
        exclusion_data = json.load(f)

    if verbose:
        n_bad = len(exclusion_data.get('bad_channels', []))
        n_good = len(exclusion_data.get('good_channels', []))
        thresholds = exclusion_data.get('thresholds_db', {})
        print("\n" + "=" * 70)
        print("STAGE A EXCLUSION LIST LOADED (TASK 3.1.1)")
        print("=" * 70)
        print(f"Subject:          {exclusion_data['subject_id']}")
        print(f"Source file:      {json_path.name}")
        print(f"Amplitude range:  [{thresholds.get('low', '?')}, "
              f"{thresholds.get('high', '?')}] dB")
        print(f"Good channels:    {n_good}")
        print(f"Bad channels:     {n_bad}")
        if n_bad > 0:
            print("  Candidate exclusions:")
            reasons = exclusion_data.get('exclusion_reasons', {})
            for ch in exclusion_data['bad_channels']:
                reason = reasons.get(ch, 'unknown')
                print(f"    - {ch}  ({reason})")
        print("=" * 70 + "\n")

    return exclusion_data


